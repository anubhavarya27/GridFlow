-- GridFlow TimescaleDB benchmark objects. Safe to rerun; does not drop existing data.
CREATE EXTENSION IF NOT EXISTS timescaledb;

-- Aggregate only Valid readings, matching the raw benchmark query.
CREATE MATERIALIZED VIEW IF NOT EXISTS public.meter_reading_daily
WITH (timescaledb.continuous) AS
SELECT
    time_bucket(INTERVAL '1 day', reading_date) AS bucket,
    meter_id,
    COUNT(*)::bigint AS reading_count,
    AVG(reading_value)::numeric AS avg_reading_value,
    MIN(reading_value)::numeric AS min_reading_value,
    MAX(reading_value)::numeric AS max_reading_value
FROM public.meter_reading
WHERE reading_status = 'Valid'
GROUP BY bucket, meter_id
WITH NO DATA;

CREATE INDEX IF NOT EXISTS idx_meter_reading_daily_meter_bucket
    ON public.meter_reading_daily (meter_id, bucket DESC);

CREATE TABLE IF NOT EXISTS public.database_benchmark_history (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    executed_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    meter_id INTEGER NULL,
    from_date DATE NOT NULL,
    to_date DATE NOT NULL,
    repetitions INTEGER NOT NULL CHECK (repetitions BETWEEN 1 AND 20),
    raw_median_execution_ms DOUBLE PRECISION NOT NULL,
    aggregate_median_execution_ms DOUBLE PRECISION NOT NULL,
    raw_median_planning_ms DOUBLE PRECISION,
    aggregate_median_planning_ms DOUBLE PRECISION,
    raw_rows_processed BIGINT NOT NULL,
    aggregate_rows_processed BIGINT NOT NULL,
    results_match BOOLEAN NOT NULL
);

CREATE INDEX IF NOT EXISTS idx_database_benchmark_history_executed_at
    ON public.database_benchmark_history (executed_at DESC);

-- Populate the continuous aggregate for existing data. Safe to rerun.
CALL refresh_continuous_aggregate('public.meter_reading_daily', NULL, NULL);

