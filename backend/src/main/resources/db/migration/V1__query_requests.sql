CREATE TABLE IF NOT EXISTS public.query_request (
    request_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    requested_by BIGINT NOT NULL REFERENCES public.app_user(user_id)
        ON UPDATE CASCADE ON DELETE RESTRICT,
    query_text TEXT NOT NULL,
    status VARCHAR(12) NOT NULL DEFAULT 'PENDING'
        CHECK (status IN ('PENDING', 'APPROVED', 'REJECTED', 'FAILED')),
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    reviewed_at TIMESTAMPTZ,
    reviewed_by BIGINT REFERENCES public.app_user(user_id)
        ON UPDATE CASCADE ON DELETE SET NULL,
    rejection_reason VARCHAR(500),
    affected_rows BIGINT
);

CREATE INDEX IF NOT EXISTS idx_query_request_pending_created
    ON public.query_request (created_at DESC)
    WHERE status = 'PENDING';

CREATE INDEX IF NOT EXISTS idx_query_request_requested_by_created
    ON public.query_request (requested_by, created_at DESC);
